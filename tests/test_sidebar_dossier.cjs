'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('static/app.js','utf8');
const context={console,setTimeout,clearTimeout,document:{querySelector:()=>({})},window:{addEventListener(){}}};
vm.createContext(context);
vm.runInContext(source.slice(0,source.lastIndexOf('(async function init(){')),context);
const side=vm.runInContext(`(()=>{state.me={admin:true,name:'Admin'};state.view='detail';return sidebar()})()`,context);
assert(side.includes('data-view="launches" title="Commandes" aria-current="page"'));
assert(!side.includes('data-view="dossier"'));
assert(!side.includes('data-sidebar-folder'));
assert(!side.includes('dossier-nav-children'));
assert(!source.includes('renderDossierSummary'));
assert(source.includes('data-folder="${e(folder.slug)}"'));
assert(source.includes("if(view==='dossier'||view==='home')await launchList()"));
assert(fs.readFileSync('static/order-identification.css','utf8').includes('.lc-documents-layout:not([hidden]){grid-template-columns:minmax(0,1fr)}'));
console.log('Commandes : aucun dossier partagé dans la sidebar, onglets par commande et documents pleine largeur.');
