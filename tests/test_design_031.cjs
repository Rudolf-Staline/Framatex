'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const css=fs.readFileSync('static/design-031.css','utf8');
const html=fs.readFileSync('static/index.html','utf8');
const previous=fs.readFileSync('static/design-030.css','utf8');
assert(html.includes('family=Space+Grotesk'), 'New display typeface must load');
assert(html.includes('family=IBM+Plex+Sans'), 'New UI typeface must load');
assert(html.includes('family=IBM+Plex+Mono'), 'Monospaced business identifiers must load');
assert(html.includes('/assets/design-031.css'), 'The new stylesheet must be linked');
assert(html.indexOf('/assets/design-031.css')>html.indexOf('/assets/design-030.css'), 'The final design layer must win');
assert(!previous.includes("@import url('https://fonts.googleapis.com"), 'Old font families should not be downloaded');
assert(css.includes('--ux-font:"Onest"'));
assert(css.includes('font-variant-numeric:tabular-nums'));
assert(css.includes('.login-rebalanced h1'));
assert(css.includes('.dash-table tbody td'));
assert(css.includes('.detail-main-tabs button'));
assert(css.includes('.nav-btn.active'));
assert(css.includes('.modal .field input'));
assert(css.includes('@media(max-width:760px)'));
assert(css.includes('prefers-reduced-motion'));
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,'CSS braces should balance');
console.log('Framatex 0.31: typography, spacing, responsive and CSS load order OK');
