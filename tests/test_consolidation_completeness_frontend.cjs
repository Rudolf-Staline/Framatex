'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const context={console};
context.e=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
context.icon=()=>'';
vm.createContext(context);vm.runInContext(fs.readFileSync('static/workspace.js','utf8'),context);
const item={action:'open_order',order_id:'order-1',launch_id:null,launch_name:'CMD-A',folder:'bleu',area:'documents',priority:'high',title:'Pièce manquante',description:'Douane'};
context.item=item;
const html=vm.runInContext('priorityCard(item)',context);
assert(html.includes('data-workspace-order="order-1"'));
assert(html.includes('data-workspace-folder="bleu"'));
assert(html.includes('data-workspace-action="open_order"'));
let listener,opened;
const button={dataset:{workspaceAction:'open_order',workspaceOrder:'order-1',workspaceFolder:'bleu',workspaceLaunch:'',workspaceArea:'documents'},addEventListener:(type,fn)=>{listener=fn}};
context.app={querySelector:()=>null,querySelectorAll:()=>[button]};
context.orderDossierPage=async(id,folder)=>{opened=[id,folder]};
context.openLaunch=async()=>{throw Error('A launchless order must keep its actual context')};
context.showErr=error=>{throw error};
vm.runInContext('bindPriorityWidget()',context);
(async()=>{await listener();assert.deepEqual(opened,['order-1','bleu']);console.log('Priorité commande sans lancement : navigation rubrique et contexte OK');})().catch(error=>{console.error(error);process.exit(1)});
